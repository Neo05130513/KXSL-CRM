def display_name(raw_name):
    short_name = raw_name.removeprefix("郑州")
    if short_name == "江山站":
        short_name = "江山路站"
    return f"{BRAND}-{short_name}"


def request_json(url):
    request = Request(url, headers={"User-Agent": "KXSL-CRM/1.0"})
    with urlopen(request, timeout=10) as response:
        return json.loads(response.read().decode("utf-8"))


def geocode_address(address):
    if not AMAP_KEY:
        raise RuntimeError("需要先设置 AMAP_KEY，导入脚本不再生成估算坐标。")
    url = "https://restapi.amap.com/v3/geocode/geo?" + urlencode(
        {
            "key": AMAP_KEY,
            "address": address,
            "city": "郑州",
            "output": "json",
        }
    )
    data = request_json(url)
    geocodes = data.get("geocodes") or []
    if data.get("status") != "1" or not geocodes:
        raise RuntimeError(f"地址定位失败：{address}；{data.get('info') or data}")
    first = geocodes[0]
    location = first.get("location") or ""
    if "," not in location:
        raise RuntimeError(f"地址定位结果缺少坐标：{address}")
    lng, lat = [float(part) for part in location.split(",", 1)]
    return lat, lng, first.get("level") or "未知", first.get("formatted_address") or address


